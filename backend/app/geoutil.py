def province_from_locality(city: str | None) -> str | None:
    """city/district 文本 → 省级行政区全名；脏值与未知地名返回 None（不发明）。"""
    v = (city or "").strip()
    if not v or v == "市辖区" or v.isdigit():
        return None
    if v in PROVINCES:
        return v
    if v in DISTRICT_TO_PROVINCE:
        return DISTRICT_TO_PROVINCE[v]
    bare = v[:-1] if v.endswith("市") else v
    if bare in PROVINCES:  # "北京市" 已在 PROVINCES；此行防截断边界
        return bare
    hit = CITY_TO_PROVINCE.get(bare)
    if hit:
        return hit
    return None
